#!/usr/bin/env python3
"""Generate the Unicode character-class tables the binary uses for text.

The classes come from the running interpreter's Unicode database, so the
tables follow its Unicode version; the generated header records both. Run:

    python3.15 -I tools/gen_unicode_tables.py > switchboard/src/unicode_tables.rs
    python3.15 -I tools/gen_unicode_tables.py --cli > switchboard/src/cli/unicode_cli.rs
"""
import sys
import unicodedata


def ranges(predicate):
    out, start = [], None
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            hit = False  # Rust strings never contain surrogates.
        else:
            hit = predicate(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, table):
    print(f"/// {doc}")
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for low, high in table:
        print(f"    (0x{low:04X}, 0x{high:04X}),")
    print("];\n")


def emit_core():
    print("// @generated by tools/gen_unicode_tables.py; do not edit.")
    print(f"// Unicode {unicodedata.unidata_version}, from Python {sys.version.split()[0]}'s unicodedata.\n")
    emit("NOT_PRINTABLE", "Non-printable: categories Cc, Cf, Cs, Co, Cn, Zl, Zp, and Zs except U+0020.",
         ranges(lambda c: not c.isprintable()))
    emit("WHITESPACE", "Whitespace: category Zs or bidirectional class WS, B, or S.",
         ranges(lambda c: c.isspace()))
    emit("NAME_REMOVED", "Unicode categories Cf, Cc, Cs, Zl, and Zp (removed from native names).",
         ranges(lambda c: unicodedata.category(c) in {"Cf", "Cc", "Cs", "Zl", "Zp"}))


def emit_cli():
    """switchboard/src/cli/unicode_cli.rs: display width and casefold tables."""
    print("// @generated by tools/gen_unicode_tables.py --cli; do not edit.")
    print(f"// Unicode {unicodedata.unidata_version}, from Python {sys.version.split()[0]}'s unicodedata.\n")
    emit("ZERO_WIDTH", "Unicode categories Mn and Me (zero terminal cells in display_width).",
         ranges(lambda c: unicodedata.category(c) in ("Mn", "Me")))
    emit("WIDE", "East Asian width W or F (two terminal cells in display_width).",
         ranges(lambda c: unicodedata.east_asian_width(c) in ("W", "F")))
    print("/// Unicode full case folding, for characters whose folding differs from themselves.")
    print("pub const CASEFOLD: &[(u32, &str)] = &[")
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        c = chr(code)
        folded = c.casefold()
        if folded != c:
            escaped = "".join(f"\\u{{{ord(x):x}}}" for x in folded)
            print(f"    (0x{code:04X}, \"{escaped}\"),")
    print("];")


if __name__ == '__main__':
    emit_cli() if '--cli' in sys.argv[1:] else emit_core()
